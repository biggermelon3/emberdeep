using System;
using UnityEngine;

namespace CloudGarden.ShadowPuzzle
{
    [Serializable] public struct SilhouettePiece
    {
        public string label;
        public Mesh mesh;
        public Material[] materials;
        public Vector3 solutionPosition,solutionEuler,trayPosition,trayEuler;
        public ShadowPose Solution=>new ShadowPose(solutionPosition,Quaternion.Euler(solutionEuler));
        public ShadowPose Tray=>new ShadowPose(trayPosition,Quaternion.Euler(trayEuler));
    }
    [Serializable] public struct SilhouetteOutline { public Vector2[] points; }

    // One front light, everyday objects as pieces. Generated by Tools/ShadowArt/build_everyday.py and
    // MetaHackthone > Shadow Workshop > Import everyday objects. The target is rasterised from these meshes
    // at their solution poses at runtime, so swapping in a new mesh keeps the level exactly solvable.
    [CreateAssetMenu(menuName="Shadow Workshop/Silhouette level")]
    public sealed class SilhouetteLevel : ScriptableObject
    {
        public const string ResourceFolder="ShadowArt/Levels/";
        public string title,button,subtitle;
        [TextArea(2,4)] public string intro,hint,complete;
        public Color accent=new Color(.94f,.70f,.39f);
        public SilhouettePiece[] pieces=Array.Empty<SilhouettePiece>();
        // Decorative coastline drawn on the screen, in workbench metres. Scoring never uses it.
        public SilhouetteOutline[] outline=Array.Empty<SilhouetteOutline>();
        [Header("Eased win condition")]
        [Tooltip("Shadow edges within this many 4.4 mm pixels of the outline count as matching.")] public int tolerancePixels=3;
        [Range(0,1)] public float coverMin=.90f,regionMin=.80f,spillMax=.07f;
        [Tooltip("Stray shadow of any single object, relative to that object's own footprint.")][Range(0,1)] public float pieceSpillMax=.12f;
        public static SilhouetteLevel Load(string id)=>string.IsNullOrEmpty(id)?null:Resources.Load<SilhouetteLevel>(ResourceFolder+id);
    }
}
